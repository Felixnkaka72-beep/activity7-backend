// GET /health - checks that the server and database respond
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", message: "Database is not reachable." });
  }
});

// Record routes
app.use("/api/records", require("./routes/records"));

// Unknown routes
app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

// Error handler (four parameters)
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed") {
    return res.status(400).json({ message: "Request body is not valid JSON." });
  }
  if (error.type === "entity.too.large") {
    return res.status(413).json({ message: "Request body is too large." });
  }
  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Something went wrong on the server." });
});

const port = process.env.PORT || 3000;
const server = app.listen(port, "0.0.0.0", () => {
  console.log(`Server listening on port ${port}`);
  // Make sure the tables and starting records exist. A failure is logged but does not stop the server.
  initDatabase()
    .then(() => console.log("Database ready."))
    .catch((error) => console.error("Database setup skipped:", error.message));
});

// Close cleanly when the host stops or restarts the service
process.on("SIGTERM", () => {
  server.close(() => pool.end().finally(() => process.exit(0)));
});
